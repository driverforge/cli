// StubConfig is everything the stub needs to know, baked into its bundle as
// the REMOTE4 global (see stub.lua's header for each field).
type StubConfig struct {
	SessionID string
	UserID    string
	Token     string
	Handlers  []string

	BrokerHost        string
	BrokerPort        int
	BrokerTLS         bool
	SkipHostnameCheck bool
	CAPEM             string

	DriverToken     string // drv_ token; empty disables the stub's SDK
	AgentDriverName string // SDK discovery override, optional
	StubVersion     string
}

// Bundle assembles the stub driver's script: the session config, the codec
// and (when the project has a driver token) the SDK as preloaded modules,
// followed by stub.lua itself. sdk may be nil.
func Bundle(cfg StubConfig, sdk []byte) []byte {
	var b bytes.Buffer
	b.WriteString("-- Remote4 stub, generated by driverforge debug. Not the real driver.\n")
	b.WriteString("REMOTE4 = ")
	b.WriteString(luaConfig(cfg))
	b.WriteString("\n")
	preload(&b, "json", asset("json.lua"))
	if len(sdk) > 0 && cfg.DriverToken != "" {
		preload(&b, "vendor.driverforge-sdk", sdk)
	}
	b.Write(asset("stub.lua"))
	return b.Bytes()
}

func preload(b *bytes.Buffer, name string, src []byte) {
	fmt.Fprintf(b, "package.preload[%s] = function(...)\n", luaString(name))
	b.Write(src)
	if !bytes.HasSuffix(src, []byte("\n")) {
		b.WriteString("\n")
	}
	b.WriteString("end\n")
}

func luaConfig(cfg StubConfig) string {
	var b strings.Builder
	b.WriteString("{\n")
	fmt.Fprintf(&b, "  session = %s,\n", luaString(cfg.SessionID))
	fmt.Fprintf(&b, "  userId = %s,\n", luaString(cfg.UserID))
	fmt.Fprintf(&b, "  token = %s,\n", luaString(cfg.Token))
	fmt.Fprintf(&b, "  stubVersion = %s,\n", luaString(cfg.StubVersion))
	if cfg.DriverToken != "" {
		fmt.Fprintf(&b, "  driverToken = %s,\n", luaString(cfg.DriverToken))
	}
	if cfg.AgentDriverName != "" {
		fmt.Fprintf(&b, "  agentDriverName = %s,\n", luaString(cfg.AgentDriverName))
	}
	b.WriteString("  handlers = {")
	for i, h := range cfg.Handlers {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(luaString(h))
	}
	b.WriteString("},\n")
	fmt.Fprintf(&b, "  broker = { host = %s, port = %d, tls = %t, skipHostnameCheck = %t, caPem = %s },\n",
		luaString(cfg.BrokerHost), cfg.BrokerPort, cfg.BrokerTLS, cfg.SkipHostnameCheck, luaString(cfg.CAPEM))
	b.WriteString("}")
	return b.String()
}

// luaString renders s as a Lua string literal. Long strings (the CA PEM) use
// a long bracket whose level no content can close; everything else is a
// quoted literal with the usual escapes.
func luaString(s string) string {
	if strings.Contains(s, "\n") {
		level := ""
		for strings.Contains(s, "]"+level+"]") {
			level += "="
		}
		return "[" + level + "[\n" + s + "]" + level + "]"
	}
	return strconv.Quote(s) // Go and Lua agree on \", \\, \n, \t and \xNN
}

// RewriteC4z copies the built driver archive to out with its script entry
// replaced by bundle, leaving every other entry — driver.xml above all —
// byte-identical. The stub therefore inherits the real driver's structural
// hash, bindings, proxies and properties.
func RewriteC4z(c4zPath, out string, bundle []byte) error {
	r, err := zip.OpenReader(c4zPath)
	if err != nil {
		return fmt.Errorf("remote4: opening %s: %w", c4zPath, err)
	}
	defer r.Close()

	var xml []byte
	for _, f := range r.File {
		if f.Name == "driver.xml" {
			xml, err = readEntry(f)
			if err != nil {
				return err
			}
		}
	}
	if xml == nil {
		return fmt.Errorf("remote4: %s has no driver.xml", c4zPath)
	}
	script, ok := driverxml.ScriptFile(xml)
	if !ok || script == "" {
		return fmt.Errorf("remote4: driver.xml in %s declares no script file", c4zPath)
	}
	if strings.HasSuffix(script, ".encrypted") {
		return fmt.Errorf("remote4: %s is encrypted; debug builds must not be", c4zPath)
	}

	tmp, err := os.CreateTemp(dirOf(out), ".remote4-*.c4z")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	w := zip.NewWriter(tmp)
	replaced := false
	for _, f := range r.File {
		entry, err := w.CreateHeader(&zip.FileHeader{Name: f.Name, Method: zip.Deflate, Modified: f.Modified})
		if err != nil {
			return err
		}
		if f.Name == script {
			replaced = true
			if _, err := entry.Write(bundle); err != nil {
				return err
			}
			continue
		}
		data, err := readEntry(f)
		if err != nil {
			return err
		}
		if _, err := entry.Write(data); err != nil {
			return err
		}
	}
	if !replaced {
		return fmt.Errorf("remote4: %s has no %s entry to replace", c4zPath, script)
	}
	if err := w.Close(); err != nil {
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), out)
}

func readEntry(f *zip.File) ([]byte, error) {
	rc, err := f.Open()
	if err != nil {
		return nil, err
	}
	defer rc.Close()
	return io.ReadAll(rc)
}

func dirOf(path string) string {
	if i := strings.LastIndexAny(path, `/\`); i >= 0 {
		return path[:i]
	}
	return "."
}
