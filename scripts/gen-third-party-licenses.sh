#!/usr/bin/env sh
# Regenerates THIRD_PARTY_LICENSES.md from the modules actually linked into the
# driverforge binary (go list -deps ./cmd/...), pulling each module's license
# text from the local Go module cache. Run from the repo root:
#
#   ./scripts/gen-third-party-licenses.sh > THIRD_PARTY_LICENSES.md
#
# Run `go mod download` first if the module cache is cold.
set -eu

GOMODCACHE=$(go env GOMODCACHE)

cat <<'EOF'
# Third-party licenses

The `driverforge` binary statically links the open-source Go modules listed
below. Each module's license text is reproduced verbatim from the version we
build against.

This file is generated by `scripts/gen-third-party-licenses.sh` — do not edit
by hand; rerun the script after dependency changes.

## The Go standard library and runtime

Binaries produced from this repository include the Go standard library and
runtime, Copyright 2009 The Go Authors, licensed under a BSD-3-Clause license:
https://go.dev/LICENSE

EOF

go list -deps -f '{{with .Module}}{{.Path}}@{{.Version}}{{end}}' ./cmd/... \
  | sort -u | grep -v '^$' | grep -v '^github.com/driverforge/cli' \
  | while IFS= read -r mod; do
    # Module cache escaping: uppercase letters become !<lowercase>.
    esc=$(printf '%s' "$mod" | sed 's/\([A-Z]\)/!\l\1/g')
    dir="$GOMODCACHE/${esc%@*}@${esc#*@}"
    lic=$(find "$dir" -maxdepth 1 \( -iname 'LICENSE*' -o -iname 'COPYING*' \) 2>/dev/null | head -1)
    if [ -z "$lic" ]; then
      echo "error: no license file found for $mod in $dir" >&2
      exit 1
    fi
    printf '## %s (%s)\n\n```\n' "${mod%@*}" "${mod#*@}"
    cat "$lic"
    printf '```\n\n'
  done
